# ROUTE 6: UPDATE APPOINTMENT STATUS (ACCEPT/REJECT)
# ---------------------------------------------------------
@app.route('/api/appointments/<int:appointment_id>/status', methods=['PUT'])
def update_appointment_status(appointment_id):
    data = request.json
    new_status = data.get('status') # Expecting: 'accepted' or 'rejected'

    if new_status not in ['accepted', 'rejected']:
        return jsonify({"error": "Invalid status update value"}), 400

    cursor = mysql.connection.cursor()
    try:
        # Update the specific appointment record execution row
        cursor.execute("""
            UPDATE appointments 
            SET status = %s 
            WHERE id = %s
        """, (new_status, appointment_id))
        
        mysql.connection.commit()
        return jsonify({"message": f"Appointment successfully {new_status}!"}), 200
    except Exception as e:
        mysql.connection.rollback()
        return jsonify({"error": str(e)}), 500
    finally:
        cursor.close()

