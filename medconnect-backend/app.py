from flask import Flask, request, jsonify
from flask_cors import CORS
from flask_mysqldb import MySQL
import bcrypt
import jwt
import datetime
from config import Config

# Initialize the Flask application
app = Flask(__name__)
app.config.from_object(Config)

# Enable CORS so our React frontend can talk to our API safely
CORS(app)

# Link MySQL to our Flask app using our config values
mysql = MySQL(app)

# ---------------------------------------------------------
# ROUTE 1: USER REGISTRATION (PATIENTS & DOCTORS)
# ---------------------------------------------------------
@app.route('/api/auth/register', methods=['POST'])
def register():
    data = request.json
    email = data.get('email')
    password = data.get('password')
    role = data.get('role')  # Expecting: 'patient' or 'doctor'
    name = data.get('name')

    # Basic Validation
    if not email or not password or not role or not name:
        return jsonify({"error": "All fields are required"}), 400

    # Securely hash the password using bcrypt
    hashed_password = bcrypt.hashpw(password.encode('utf-8'), bcrypt.gensalt()).decode('utf-8')

    cursor = mysql.connection.cursor()
    try:
        # Step A: Insert into the core users authentication table
        cursor.execute(
            "INSERT INTO users (email, password_hash, role) VALUES (%s, %s, %s)", 
            (email, hashed_password, role)
        )
        user_id = cursor.lastrowid # Grabs the unique ID generated by AUTO_INCREMENT

        # Step B: Insert into profile tables depending on their role
        if role == 'patient':
            cursor.execute("INSERT INTO patients (user_id, name) VALUES (%s, %s)", (user_id, name))
        elif role == 'doctor':
            # Setting default placeholder values for specialization and fee
            cursor.execute(
                "INSERT INTO doctors (user_id, name, specialization, fees) VALUES (%s, %s, 'General Physician', 500.00)", 
                (user_id, name)
            )
        
        mysql.connection.commit()
        return jsonify({"message": "Registration successful!"}), 201

    except Exception as e:
        mysql.connection.rollback() # Undo changes if something goes wrong
        return jsonify({"error": "Email already exists or database error", "details": str(e)}), 400
    finally:
        cursor.close()

# ---------------------------------------------------------
# ROUTE 2: USER LOGIN (GENERATES SECURE JWT TOKEN)
# ---------------------------------------------------------
@app.route('/api/auth/login', methods=['POST'])
def login():
    data = request.json
    email = data.get('email')
    password = data.get('password')

    cursor = mysql.connection.cursor()
    # Fetch user password hash and role matching the email
    cursor.execute("SELECT id, password_hash, role FROM users WHERE email = %s", (email,))
    user = cursor.fetchone()
    cursor.close()

    # If user exists, check if the password matches the hash
    if user and bcrypt.checkpw(password.encode('utf-8'), user[1].encode('utf-8')):
        # Create a JWT token valid for 24 hours
        token = jwt.encode({
            'user_id': user[0],
            'role': user[2],
            'exp': datetime.datetime.utcnow() + datetime.timedelta(hours=24)
        }, app.config['SECRET_KEY'], algorithm='HS256')

        return jsonify({
            "token": token,
            "role": user[2],
            "message": "Login successful!"
        }), 200
    
    return jsonify({"error": "Invalid email or password"}), 401

