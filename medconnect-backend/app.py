# ROUTE 3: GET ALL AVAILABLE DOCTORS (ROBUST POSITION)
# ---------------------------------------------------------
@app.route('/api/doctors', methods=['GET'])
def get_doctors():
    cursor = mysql.connection.cursor()
    try:
        # Simplified query to ensure items populate the frontend seamlessly
        cursor.execute("""
            SELECT id, name, specialization, fees 
            FROM doctors 
            WHERE availability_status = TRUE
        """)
        columns = [col[0] for col in cursor.description]
        doctors = [dict(zip(columns, row)) for row in cursor.fetchall()]
        
        return jsonify(doctors), 200
    except Exception as e:
        return jsonify({"error": str(e)}), 500
    finally:
        cursor.close()

