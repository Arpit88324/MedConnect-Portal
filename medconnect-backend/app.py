# ROUTE 4: BOOK AN APPOINTMENT
# ---------------------------------------------------------
@app.route('/api/appointments/book', methods=['POST'])
def book_appointment():
    data = request.json
    patient_id = data.get('patient_id')  
    doctor_id = data.get('doctor_id')
    appointment_date = data.get('appointment_date') 

    if not patient_id or not doctor_id or not appointment_date:
        return jsonify({"error": "Missing booking details"}), 400

    cursor = mysql.connection.cursor()
    try:
        cursor.execute(
            "INSERT INTO appointments (patient_id, doctor_id, appointment_date, status) VALUES (%s, %s, %s, 'pending')",
            (patient_id, doctor_id, appointment_date)
        )
        mysql.connection.commit()
        return jsonify({"message": "Appointment booked successfully!"}), 201
    except Exception as e:
        mysql.connection.rollback()
        return jsonify({"error": str(e)}), 500
    finally:
        cursor.close()

# ---------------------------------------------------------
# ROUTE 5: GET APPOINTMENTS FOR A SPECIFIC DOCTOR (UPDATED & MOVED)
# ---------------------------------------------------------
@app.route('/api/doctor/<int:doctor_id>/appointments', methods=['GET'])
def get_doctor_appointments(doctor_id):
    cursor = mysql.connection.cursor()
    try:
        # LEFT JOIN ensures appointments show up even if profiles desync temporarily
        cursor.execute("""
            SELECT a.id, a.appointment_date, a.status, COALESCE(p.name, 'Default Patient') AS patient_name 
            FROM appointments a
            LEFT JOIN patients p ON a.patient_id = p.id
            WHERE a.doctor_id = %s
            ORDER BY a.appointment_date ASC
        """, (doctor_id,))
        
        columns = [col[0] for col in cursor.description]
        appointments = [dict(zip(columns, row)) for row in cursor.fetchall()]
        
        return jsonify(appointments), 200
    except Exception as e:
        return jsonify({"error": str(e)}), 500
    finally:
        cursor.close()
